const express=require('express');
const {authenticate,authorize}=require('../middleware/auth');
const {createService}=require('../services/paymentDiary');
const service=createService(require('../config/db'));
const router=express.Router();
router.use(authenticate,authorize('SERVER','ADMIN'));
const endpoint=work=>async(req,res)=>{try{res.json(await work(req));}catch(error){const duplicate=error.code==='ER_DUP_ENTRY';res.status(error.status||(duplicate?409:500)).json({error:error.status?error.message:duplicate?'This bill or request has already been recorded. Refresh the diary before trying again.':'Unable to complete the diary operation. Your ledger has not been partially updated.'});}};
const id=req=>{const value=Number(req.params.id);if(!Number.isSafeInteger(value)||value<=0)throw Object.assign(new Error('Invalid record.'),{status:400});return value;};
router.get('/',endpoint(req=>service.list(req.query)));
router.get('/accounts',endpoint(req=>service.accounts(req.query)));
router.post('/',endpoint(req=>service.add(req.body,req.user.username)));
router.post('/close-year',endpoint(req=>service.closeYear(req.body,req.user.username)));
router.get('/:id/payments',endpoint(req=>service.history(id(req))));
router.get('/:id/changes',endpoint(req=>service.changes(id(req))));
router.put('/:id',endpoint(req=>service.modify(id(req),req.body,req.user.username)));
router.delete('/:id',endpoint(req=>service.modify(id(req),req.body,req.user.username,'DELETE')));
router.post('/:id/restore',endpoint(req=>service.modify(id(req),req.body,req.user.username,'RESTORE')));
router.post('/:id/payments',endpoint(req=>service.pay(id(req),req.body,req.user.username)));
router.post('/payments/:id/reverse',endpoint(req=>service.reverse(id(req),req.body,req.user.username)));
module.exports=router;
